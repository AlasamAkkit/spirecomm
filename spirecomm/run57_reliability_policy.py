"""v1.7.2 narrow card-reward JSON validation and auditable recovery helpers.

This module never chooses gameplay actions, rewrites memory or changes history.
Only a small, unambiguous subset of score spelling mistakes is normalized.
All other invalid output must be regenerated by the LLM or cause a safe pause.
"""
from __future__ import annotations

import json
import math
import re
from pathlib import Path
from typing import Any

from run55_policy import parse_json_object

_NUMBER_WORDS = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4,
    "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9,
    "ten": 10, "eleven": 11, "twelve": 12, "thirteen": 13,
    "fourteen": 14, "fifteen": 15, "sixteen": 16, "seventeen": 17,
    "eighteen": 18, "nineteen": 19, "twenty": 20, "thirty": 30,
    "forty": 40, "fifty": 50, "sixty": 60, "seventy": 70,
    "eighty": 80, "ninety": 90, "hundred": 100,
}
_SCORES_OBJECT = re.compile(r'"scores"\s*:\s*\{(?P<body>[^{}]*)\}', re.DOTALL)
_BARE_SCORE_WORD = re.compile(
    r'(?P<prefix>"(?:0|[1-9]\d*)"\s*:\s*)'
    r'(?P<word>[a-zA-Z]+)'
    r'(?=\s*(?:,|$))'
)


def normalize_score_words(text: str) -> tuple[str, list[dict[str, Any]]]:
    """Replace known bare English *numeric score values* only.

    Never touch instructions, plan narrative, strings, card names, or scores
    whose meaning cannot be interpreted unambiguously. The resulting JSON
    must still pass standard parsing and complete score validation.
    """
    found = _SCORES_OBJECT.search(text)
    if not found:
        return text, []
    fixes: list[dict[str, Any]] = []

    def replace(match: re.Match[str]) -> str:
        word = match.group("word").lower()
        if word not in _NUMBER_WORDS:
            return match.group(0)
        index = re.search(r'"\d+"', match.group("prefix"))
        if index is None:
            return match.group(0)
        number = _NUMBER_WORDS[word]
        fixes.append({"index": index.group(0).strip('"'),
                      "original_word": match.group("word"), "number": number})
        return match.group("prefix") + str(number)

    replacement = _BARE_SCORE_WORD.sub(replace, found.group("body"))
    if not fixes:
        return text, []
    return text[:found.start("body")] + replacement + text[found.end("body"):], fixes


def parse_card_reward_json(text: str) -> dict[str, Any]:
    """Keep prior safe trailing-comma handling; repair score words if needed."""
    try:
        return parse_json_object(text)
    except (ValueError, json.JSONDecodeError):
        normalized, fixes = normalize_score_words(text)
        if not fixes:
            raise
        return parse_json_object(normalized)


def legal_action_count(prompt: str) -> int:
    """Recover the action count from v1.2's numbered LEGAL ACTIONS section."""
    if "\nLEGAL ACTIONS\n" not in prompt:
        raise ValueError("Card-reward prompt has no numbered LEGAL ACTIONS section")
    section = prompt.split("\nLEGAL ACTIONS\n", 1)[1]
    if "\n\nSTEP 1" not in section:
        raise ValueError("Card-reward prompt has no STEP 1 boundary")
    section = section.split("\n\nSTEP 1", 1)[0]
    numbers = [
        int(match.group(1))
        for line in section.splitlines()
        if (match := re.fullmatch(r"\s*(\d+): .+", line))
    ]
    if len(numbers) < 2 or len(numbers) > 20 or numbers != list(range(len(numbers))):
        raise ValueError("Card-reward legal-action indices are not contiguous")
    return len(numbers)


def validate_card_reward_payload(payload: dict[str, Any], count: int) -> dict[int, float]:
    """Validate all scores BEFORE the inherited evaluator can write a deck plan."""
    if not isinstance(payload, dict):
        raise ValueError("Card-reward response must be a JSON object")
    plan = payload.get("deck_plan")
    if not isinstance(plan, dict):
        raise ValueError("Card-reward response requires a deck_plan object")
    for key in ("offense", "defense", "scaling", "draw_energy", "aoe"):
        if not isinstance(plan.get(key), str) or not plan[key].strip():
            raise ValueError("deck_plan is missing a nonempty " + key)
    for key in ("weaknesses", "acquisition_priorities", "avoid"):
        if not isinstance(plan.get(key), list) or not all(
                isinstance(value, str) for value in plan[key]):
            raise ValueError("deck_plan requires a list of strings for " + key)
    if plan.get("add_policy") not in {"OPEN", "SELECTIVE", "SKIP_DEFAULT"}:
        raise ValueError("deck_plan.add_policy must be OPEN/SELECTIVE/SKIP_DEFAULT")
    if not isinstance(payload.get("plan_changed"), bool):
        raise ValueError("plan_changed must be boolean")
    for key in ("plan_change_reason", "reason"):
        if not isinstance(payload.get(key), str) or not payload[key].strip():
            raise ValueError(key + " must be a nonempty string")
    values = payload.get("scores")
    if not isinstance(values, dict):
        raise ValueError("scores must be an indexed JSON object")
    expected = {str(i) for i in range(count)}
    if set(values) != expected:
        raise ValueError("scores must contain exactly action keys " +
                         ", ".join(sorted(expected, key=int)))
    scores = {}
    for i in range(count):
        value = values[str(i)]
        if type(value) not in {int, float}:
            raise ValueError(f"score {i} must be a JSON number, not {type(value).__name__}")
        if not math.isfinite(value) or not (0 <= value <= 100):
            raise ValueError(f"score {i} must be finite and within 0-100")
        scores[i] = float(value)
    return scores


def unfinished_attempt(events_file: Path) -> dict[str, Any] | None:
    """Find the most recent RUN_START lacking a RUN_END, without mutating logs.

    A subsequent new RUN_START after a model-parse pause is a NEW ATTEMPT,
    not a resumption. Check for a prior audit marker to remain idempotent.
    """
    events_file = Path(events_file)
    if not events_file.is_file():
        return None
    latest: dict[str, Any] | None = None
    ended: set[str] = set()
    audited: set[str] = set()
    pause_reasons: dict[str, str] = {}
    with events_file.open("r", encoding="utf-8") as stream:
        for number, line in enumerate(stream, 1):
            if not line.strip():
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid event JSON at line {number}") from exc
            run_id = event.get("run_id")
            event_type = event.get("event_type")
            if event_type == "RUN_START" and run_id:
                latest = event
            elif event_type == "RUN_END" and run_id:
                ended.add(run_id)
            elif event_type in {
                "RUN55_CARD_REWARD_PARSE_PAUSED", "EXPERIMENT_PAUSED",
                "RUN_INTERRUPTED_INFRASTRUCTURE",
            } and run_id:
                pause_reasons[run_id] = event_type
            elif event_type == "RUN57_PREVIOUS_ATTEMPT_INTERRUPTED":
                old_id = event.get("previous_run_id")
                if old_id:
                    audited.add(old_id)
    if not latest:
        return None
    run_id = latest["run_id"]
    if run_id in ended or run_id in audited:
        return None
    return {
        "run_id": run_id,
        "requested_seed": latest.get("requested_seed"),
        "reason": pause_reasons.get(run_id, "unfinished_run_without_RUN_END"),
    }
